func GetAdvertisements(c *gin.Context) {
	advertisements, err := services.GetAllAdvertisements()
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	c.JSON(http.StatusOK, advertisements)
}

